#!/usr/bin/env node
// Converts a submitted /get-started clone_requests row into a sectionVisibility snippet
// ready for manual review/paste into a new clone's business-content.ts.
//
// Usage: node scripts/generate-clone-config.mjs <clone_request_id>

import { createClient } from "@supabase/supabase-js";
import { readFileSync, existsSync, mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, "..");

// Section keys/order must match sectionVisibility in src/lib/business-content.ts exactly.
// Verified against the drift guard below every run — see assertSectionKeysMatchSource().
const SECTION_KEYS = [
  "trustStats",
  "whyChooseUs",
  "meetTheTeam",
  "howItWorks",
  "clinicExperience",
  "reviewsMarquee",
  "clientStories",
  "healthResources",
  "carePlans",
  "faqTeaser",
  "proofStories",
  "proofCareStats",
  "aboutTeamGrid",
  "teamProvidersGrid",
  "providerAreasOfInterest",
  "relatedArticles",
  "locationServicesAndHours",
];

// Fails loudly instead of silently generating a wrong snippet if SECTION_KEYS above ever
// drifts from the real `sectionVisibility` export in business-content.ts (e.g. a key gets
// renamed/added/removed there and this script isn't updated to match).
function assertSectionKeysMatchSource() {
  const sourcePath = path.join(rootDir, "src", "lib", "business-content.ts");
  const source = readFileSync(sourcePath, "utf8");
  const match = source.match(/export const sectionVisibility = \{([\s\S]*?)\n\};/);
  if (!match) {
    fail(`Could not locate "export const sectionVisibility = { ... };" in ${path.relative(rootDir, sourcePath)}.`);
  }
  const realKeys = [...match[1].matchAll(/^\s*(\w+):/gm)].map((m) => m[1]);

  const missing = realKeys.filter((key) => !SECTION_KEYS.includes(key));
  const stale = SECTION_KEYS.filter((key) => !realKeys.includes(key));
  if (missing.length > 0 || stale.length > 0) {
    fail(
      "SECTION_KEYS in this script has drifted from the real sectionVisibility export in business-content.ts. " +
        `Missing (in source but not here): ${missing.join(", ") || "(none)"}. ` +
        `Stale (here but not in source): ${stale.join(", ") || "(none)"}. ` +
        "Update SECTION_KEYS to match before running this script."
    );
  }
}

assertSectionKeysMatchSource();

function loadEnvFile(filename) {
  const filePath = path.join(rootDir, filename);
  if (!existsSync(filePath)) return;
  for (const line of readFileSync(filePath, "utf8").split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    const value = trimmed.slice(eq + 1).trim().replace(/^["']|["']$/g, "");
    if (!(key in process.env)) process.env[key] = value;
  }
}

// .env.local takes precedence over .env, mirroring Next.js's own load order.
loadEnvFile(".env");
loadEnvFile(".env.local");

function fail(message) {
  console.error(`Error: ${message}`);
  process.exit(1);
}

const cloneRequestId = process.argv[2];
if (!cloneRequestId) {
  fail("Missing required argument <clone_request_id>. Usage: node scripts/generate-clone-config.mjs <clone_request_id>");
}

const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL;
const serviceRoleKey = process.env.SUPABASE_SERVICE_ROLE_KEY;

if (!supabaseUrl || !serviceRoleKey) {
  fail(
    "NEXT_PUBLIC_SUPABASE_URL and/or SUPABASE_SERVICE_ROLE_KEY are not set (checked process.env, .env, .env.local). " +
      "Configure these before running this script."
  );
}

const supabase = createClient(supabaseUrl, serviceRoleKey, {
  auth: { autoRefreshToken: false, persistSession: false },
});

const { data: row, error } = await supabase
  .from("clone_requests")
  .select("*")
  .eq("id", cloneRequestId)
  .single();

if (error || !row) {
  fail(`No clone_requests row found for id "${cloneRequestId}" (${error?.message ?? "not found"}).`);
}

const sectionContent = row.section_content ?? {};
const missingKeys = SECTION_KEYS.filter((key) => typeof sectionContent[key] !== "boolean");
if (missingKeys.length > 0) {
  fail(`Row's section_content is missing or has non-boolean values for: ${missingKeys.join(", ")}`);
}

const sectionVisibilityLines = SECTION_KEYS.map((key) => `  ${key}: ${sectionContent[key]},`).join("\n");

const header = [
  "// Generated by scripts/generate-clone-config.mjs — review before pasting into a new clone.",
  `// clone_requests.id: ${row.id}`,
  `// businessName: ${row.business_name ?? ""}`,
  `// contactName: ${row.contact_name ?? ""}`,
  `// contactEmail: ${row.contact_email ?? ""}`,
  `// contactPhone: ${row.contact_phone ?? ""}`,
  `// niche: ${row.niche ?? ""}`,
  `// numberOfLocations: ${row.number_of_locations ?? ""}`,
  `// currentBookingSystem: ${row.current_booking_system ?? ""}`,
  `// notes: ${row.notes ?? ""}`,
].join("\n");

const snippet = `${header}

export const sectionVisibility = {
${sectionVisibilityLines}
};
`;

const outputDir = path.join(rootDir, "scripts", "output");
mkdirSync(outputDir, { recursive: true });
const outputPath = path.join(outputDir, `clone-config-${cloneRequestId}.ts`);
writeFileSync(outputPath, snippet, "utf8");

const yesCount = SECTION_KEYS.filter((key) => sectionContent[key] === true).length;
const noCount = SECTION_KEYS.length - yesCount;

console.log(`Business: ${row.business_name ?? "(unknown)"}`);
console.log(`Niche: ${row.niche ?? "(unknown)"}`);
console.log(`Sections: ${yesCount} yes / ${noCount} no (of ${SECTION_KEYS.length})`);
console.log(`Output: ${path.relative(rootDir, outputPath)}`);
